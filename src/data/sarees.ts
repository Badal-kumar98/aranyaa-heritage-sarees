const enrich = (s: SareeSeed): Saree => ({
  ...s,
  currency: 'INR',
  primaryImage: s.images[0],
  detailImages: s.detailImages ?? {},
  assetSource: 'generated',
  assetRoles: ['model', 'pallu', 'border', 'fabric'],
});

// Duplicate & remix into a 36-item catalogue so PLPs feel real, without
// generating dozens of unique product records. Each remix relabels name/
// price/colours so the storefront stays coherent when browsed.
const REMIX_SUFFIXES = ['II', 'III', 'in Alt Palette'];
const REMIX_COLORS: Array<{ name: string; hex: string }> = [
  { name: 'Charcoal', hex: '#2b2b2b' },
  { name: 'Ivory', hex: '#efe7d0' },
  { name: 'Rose', hex: '#c47a7a' },
  { name: 'Ochre', hex: '#c8952a' },
];

const expanded: Saree[] = [];
RAW.forEach((s, i) => {
  expanded.push(enrich(s));
  REMIX_SUFFIXES.forEach((sfx, j) => {
    const color = REMIX_COLORS[(i + j) % REMIX_COLORS.length];
    const priceJitter = 1 + ((i + j) % 5) * 0.05 - 0.1;
    expanded.push(
      enrich({
        ...s,
        id: `${s.id}-${sfx.toLowerCase().replace(/\s/g, '-')}`,
        slug: `${s.slug}-${sfx.toLowerCase().replace(/\s/g, '-')}`,
        name: `${s.name} — ${sfx}`,
        shortName: `${s.shortName} ${sfx}`,
        price: Math.round((s.price * priceJitter) / 100) * 100,
        colors: [color, ...s.colors],
        primaryColor: color,
        badges: sfx === 'II' ? s.badges : s.badges.filter((b) => b !== 'new'),
        stock: Math.max(1, s.stock - j),
      })
    );
  });
});

export const SAREES: Saree[] = expanded;
